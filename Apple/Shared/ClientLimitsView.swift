import ProxyGaugeCore
import ProxyGaugeSession
import SwiftUI

struct ClientLimitsView: View {
    let session: ServerSession

    var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: 20) {
                SessionStatusBanner(session: session, scope: .limits)
                if let limits = session.fleetLimits {
                    content(limits)
                } else if let savedAt = session.quotaOverview(at: .now).savedAt {
                    savedContent(savedAt: savedAt)
                } else if session.limitsLoaded {
                    ContentUnavailableView {
                        Label("No quota data for client keys", systemImage: "speedometer")
                    } description: {
                        Text("This server answered 404 for /v1/fleet/limits, so it does not share quota with client keys. Stock CLIProxyAPI does not have this endpoint. The model list still works; for quotas, add the server with its management key.")
                    }
                    .boardCard()
                } else {
                    NotLoadedRow(phase: session.loadPhase(for: .limits, loaded: false))
                        .frame(maxWidth: .infinity, alignment: .leading)
                        .boardCard()
                }
            }
            .padding()
        }
        .background(BoardStyle.pageBackground)
    }

    private var clientKeyNote: Text {
        Text("Refresh from provider requires a management key. A client key cannot ask the server to contact providers.")
    }

    @ViewBuilder
    private func content(_ limits: FleetLimits) -> some View {
        let accounts = session.accountSummaries
        if let generatedAt = limits.generatedAt {
            ElapsedText(since: generatedAt) { Text("Generated by the server \($0) ago from quota samples it already holds.") }
                .font(.caption)
                .foregroundStyle(.secondary)
        }
        Label {
            clientKeyNote
                .fixedSize(horizontal: false, vertical: true)
        } icon: {
            Image(systemName: "key")
        }
        .font(.caption)
        .foregroundStyle(.secondary)
        DashboardSection(title: "Pooled capacity") {
            DashboardInfoButton()
        } content: {
            ProviderTilesGrid(pools: session.pools, headroom: session.headroom, accounts: accounts, phase: .loaded)
        }
        DashboardSection(title: "Credentials") {
            if accounts.isEmpty {
                Text("No credentials are visible to this client key.")
                    .foregroundStyle(.secondary)
                    .frame(maxWidth: .infinity, alignment: .leading)
                    .boardCard()
            } else {
                VStack(alignment: .leading, spacing: 12) {
                    AccountCardGroups(session: session, ordered: AccountOrder.ordered(accounts, mode: .stock, now: .now), now: .now)
                }
            }
        }
        if !limits.exclusions.isEmpty {
            DashboardSection(title: "Excluded models") {
                VStack(alignment: .leading, spacing: 10) {
                    ForEach(limits.exclusions, id: \.self) { exclusion in
                        ExclusionRow(exclusion: exclusion)
                    }
                }
                .frame(maxWidth: .infinity, alignment: .leading)
                .boardCard()
            }
        }
    }

    @ViewBuilder
    private func savedContent(savedAt: Date) -> some View {
        let quota = session.quotaOverview(at: .now)
        SavedDataNote(savedAt: savedAt, refreshesAutomatically: session.refreshesAutomatically)
        DashboardSection(title: "Pooled capacity") {
            DashboardInfoButton()
        } content: {
            ProviderTilesGrid(pools: quota.pools, headroom: quota.headroom, accounts: [], phase: session.loadPhase(for: .limits, loaded: false))
        }
    }
}

private struct ExclusionRow: View {
    let exclusion: FleetExclusion

    var body: some View {
        VStack(alignment: .leading, spacing: 2) {
            Text(verbatim: exclusion.pattern).font(.callout.monospaced())
            HStack(spacing: 4) {
                if let provider = exclusion.provider {
                    Text(ProviderCatalog.displayName(provider))
                }
                Text(verbatim: "·")
                exclusion.source == "key-policy" ? Text("Key policy") : Text("Excluded by the server")
                if let until = exclusion.until {
                    Text("until \(Text(until, format: .dateTime.month().day().hour().minute()))")
                }
            }
            .font(.caption)
            .foregroundStyle(.secondary)
        }
    }
}
