import ProxyGaugeCore
import ProxyGaugeSession
import SwiftUI

struct ClientLimitsView: View {
    let session: ServerSession

    var body: some View {
        List {
            SessionStatusSection(session: session, scope: .limits)
            if let limits = session.fleetLimits {
                content(limits)
            } else if session.limitsLoaded {
                Section {
                    ContentUnavailableView {
                        Label("No quota data for client keys", systemImage: "speedometer")
                    } description: {
                        Text("This server answered 404 for /v1/fleet/limits, so it does not share quota with client keys. Stock CLIProxyAPI does not have this endpoint. The model list still works; for quotas, add the server with its management key.")
                    }
                }
            } else {
                Section { NotLoadedRow(phase: session.loadPhase(for: .limits, loaded: false)) }
            }
        }
    }

    @ViewBuilder
    private func content(_ limits: FleetLimits) -> some View {
        Section {
            ForEach(HeadroomCalculator.fromFleet(limits)) { provider in
                ProviderHeadroomRow(headroom: provider)
                    .padding(.vertical, 2)
            }
        } header: {
            Text("Headroom per provider")
        } footer: {
            if let generatedAt = limits.generatedAt {
                Text("Generated by the server \(Text(generatedAt, style: .relative)) ago from quota samples it already holds.")
            }
        }
        Section("Credentials") {
            ForEach(limits.credentials) { credential in
                FleetCredentialRow(credential: credential)
            }
            if limits.credentials.isEmpty {
                Text("No credentials are visible to this client key.").foregroundStyle(.secondary)
            }
        }
        if !limits.exclusions.isEmpty {
            Section {
                ForEach(limits.exclusions, id: \.self) { exclusion in
                    VStack(alignment: .leading, spacing: 2) {
                        Text(verbatim: exclusion.pattern).font(.callout.monospaced())
                        HStack(spacing: 4) {
                            if let provider = exclusion.provider {
                                Text(ProviderCatalog.displayName(provider))
                            }
                            Text(verbatim: "·")
                            exclusion.source == "key-policy" ? Text("Key policy") : Text("Excluded by the server")
                            if let until = exclusion.until {
                                Text("until \(Text(until, format: .dateTime.month().day().hour().minute()))")
                            }
                        }
                        .font(.caption)
                        .foregroundStyle(.secondary)
                    }
                }
            } header: {
                Text("Excluded models")
            }
        }
    }
}

private struct FleetCredentialRow: View {
    let credential: FleetCredential

    var body: some View {
        VStack(alignment: .leading, spacing: 6) {
            HStack(spacing: 8) {
                ProviderBadge(provider: credential.provider, size: 22)
                Text(verbatim: credential.label).font(.body.weight(.medium))
                if let plan = credential.plan {
                    Text(verbatim: plan.capitalized)
                        .font(.caption2.weight(.semibold))
                        .padding(.horizontal, 5)
                        .padding(.vertical, 1)
                        .background(.quaternary, in: .capsule)
                }
                Spacer()
                StateBadge(state: credential.credentialState)
            }
            ForEach(credential.bars.map(\.quotaBar).sortedForDisplay()) { bar in
                QuotaBarRow(bar: bar)
            }
            ForEach(credential.cooldowns, id: \.self) { cooldown in
                if let until = cooldown.until, until > .now {
                    Text("\(cooldown.model ?? String(localized: "Whole account")) cooling down for \(Text(until, style: .relative))")
                        .font(.caption)
                        .foregroundStyle(.orange)
                }
            }
            if let balance = credential.credits?.balance {
                Text("Credits: \(balance.formatted(.number.precision(.fractionLength(0...2))))")
                    .font(.caption)
                    .foregroundStyle(.secondary)
            }
        }
        .padding(.vertical, 2)
    }
}
